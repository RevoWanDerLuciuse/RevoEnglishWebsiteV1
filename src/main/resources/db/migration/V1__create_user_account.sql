-- Accounts for the private portal: students (created by the teacher) and administrators.
-- No lesson, subscription or contact data is stored here.
CREATE TABLE user_account (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name             VARCHAR(100)             NOT NULL,
    -- Username or e-mail used to sign in; stored trimmed and lower-cased, so the unique
    -- constraint is effectively case-insensitive.
    login                    VARCHAR(254)             NOT NULL,
    -- Spring Security DelegatingPasswordEncoder format, e.g. "{bcrypt}$2a$10$…". Never plaintext.
    password_hash            VARCHAR(255)             NOT NULL,
    role                     VARCHAR(20)              NOT NULL,
    active                   BOOLEAN                  NOT NULL,
    password_change_required BOOLEAN                  NOT NULL,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_account_login UNIQUE (login),
    CONSTRAINT ck_user_account_login_lowercase CHECK (login = LOWER(login)),
    CONSTRAINT ck_user_account_role CHECK (role IN ('STUDENT', 'ADMIN')),
    CONSTRAINT ck_user_account_display_name CHECK (LENGTH(display_name) > 0)
);
