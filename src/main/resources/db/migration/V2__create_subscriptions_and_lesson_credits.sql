-- Student subscriptions, manual payment records and the lesson-credit ledger.
-- Plan definitions are not stored here: they live in PricingCatalog. A subscription keeps a snapshot of the
-- plan (name, lessons, price) taken when it was assigned, so later price changes never affect it.
-- Money is stored as BIGINT minor units (kopecks) with an explicit currency — never floating point.

CREATE TABLE subscription (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id           BIGINT                   NOT NULL REFERENCES user_account (id),
    plan_code            VARCHAR(20)              NOT NULL,
    plan_name            VARCHAR(50)              NOT NULL,
    lessons_included     INTEGER                  NOT NULL,
    lesson_minutes       INTEGER                  NOT NULL,
    -- Agreed price of this subscription: the plan price at assignment, 0 for a complimentary one
    price_minor          BIGINT                   NOT NULL,
    currency             VARCHAR(3)               NOT NULL,
    complimentary        BOOLEAN                  NOT NULL,
    complimentary_reason VARCHAR(500),
    status               VARCHAR(20)              NOT NULL,
    starts_on            DATE                     NOT NULL,
    expires_on           DATE                     NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by           BIGINT                   NOT NULL REFERENCES user_account (id),
    activated_at         TIMESTAMP WITH TIME ZONE,
    activated_by         BIGINT REFERENCES user_account (id),
    -- Set when the subscription is cancelled or expires; closed_by is NULL for the automatic daily expiry
    closed_at            TIMESTAMP WITH TIME ZONE,
    closed_by            BIGINT REFERENCES user_account (id),
    close_reason         VARCHAR(500),
    -- One key per submitted "assign" form, so a double submit cannot create two subscriptions
    request_key          VARCHAR(100)             NOT NULL,
    version              BIGINT                   NOT NULL,
    CONSTRAINT uk_subscription_request UNIQUE (request_key),
    CONSTRAINT ck_subscription_status CHECK (status IN ('PENDING_PAYMENT', 'ACTIVE', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_subscription_lessons CHECK (lessons_included > 0),
    CONSTRAINT ck_subscription_minutes CHECK (lesson_minutes > 0),
    CONSTRAINT ck_subscription_price CHECK (price_minor >= 0),
    CONSTRAINT ck_subscription_currency CHECK (currency = 'RUB'),
    CONSTRAINT ck_subscription_dates CHECK (expires_on >= starts_on),
    CONSTRAINT ck_subscription_complimentary CHECK (
        complimentary = FALSE OR (price_minor = 0 AND complimentary_reason IS NOT NULL)),
    CONSTRAINT ck_subscription_activation CHECK (
        status = 'PENDING_PAYMENT' OR (activated_at IS NOT NULL AND activated_by IS NOT NULL) OR status = 'CANCELLED')
);

CREATE INDEX idx_subscription_student ON subscription (student_id);

-- Payments are recorded manually by the teacher; there is no online payment.
CREATE TABLE subscription_payment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT                   NOT NULL REFERENCES subscription (id),
    amount_minor    BIGINT                   NOT NULL,
    currency        VARCHAR(3)               NOT NULL,
    paid_on         DATE                     NOT NULL,
    note            VARCHAR(500),
    recorded_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_by     BIGINT                   NOT NULL REFERENCES user_account (id),
    request_key     VARCHAR(100)             NOT NULL,
    CONSTRAINT uk_subscription_payment_request UNIQUE (request_key),
    CONSTRAINT ck_subscription_payment_amount CHECK (amount_minor > 0),
    CONSTRAINT ck_subscription_payment_currency CHECK (currency = 'RUB')
);

CREATE INDEX idx_subscription_payment_subscription ON subscription_payment (subscription_id);

-- Append-only ledger. The balance of a subscription is SUM(delta); it is never stored separately.
CREATE TABLE lesson_credit_transaction (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id         BIGINT                   NOT NULL REFERENCES subscription (id),
    type                    VARCHAR(20)              NOT NULL,
    delta                   INTEGER                  NOT NULL,
    -- Which lesson was consumed: "manual:<uuid>" today, a calendar lesson id later
    lesson_ref              VARCHAR(100),
    lesson_date             DATE,
    -- A RESTORE points at the CONSUME it reverses; the unique constraint allows only one restore per lesson
    reverses_transaction_id BIGINT REFERENCES lesson_credit_transaction (id),
    reason                  VARCHAR(500),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    -- NULL only for future automatic operations; manual adjustments always name the administrator
    created_by              BIGINT REFERENCES user_account (id),
    -- Idempotency: "grant:<subscription>", "consume:<lesson_ref>", "restore:<transaction>", "adjust:<uuid>"
    request_key             VARCHAR(150)             NOT NULL,
    CONSTRAINT uk_credit_request UNIQUE (request_key),
    CONSTRAINT uk_credit_reverses UNIQUE (reverses_transaction_id),
    CONSTRAINT ck_credit_type CHECK (type IN ('GRANT', 'CONSUME', 'RESTORE', 'ADJUSTMENT')),
    CONSTRAINT ck_credit_shape CHECK (
        (type = 'GRANT' AND delta > 0)
        OR (type = 'CONSUME' AND delta = -1 AND lesson_ref IS NOT NULL AND lesson_date IS NOT NULL)
        OR (type = 'RESTORE' AND delta = 1 AND reverses_transaction_id IS NOT NULL AND reason IS NOT NULL)
        OR (type = 'ADJUSTMENT' AND delta <> 0 AND reason IS NOT NULL AND created_by IS NOT NULL))
);

CREATE INDEX idx_credit_subscription ON lesson_credit_transaction (subscription_id);
